const DARK = new Set(['rust', 'c', 'markdown', 'express', 'nextjs', 'threejs', 'socketio', 'flask', 'vercel', 'prisma', 'bash', 'githubactions', 'objectivec'])

export function logoFor(name: string, kind: 'language' | 'tech' = 'language'): { src: string; dark: boolean } | null {
  const slug = (kind === 'language' ? LANGUAGE_LOGOS[name] : TECH_LOGOS[name] ?? LANGUAGE_LOGOS[name])
  if (!slug) return null
  return { src: `${import.meta.env.BASE_URL}logos/${slug}.svg`, dark: DARK.has(slug) }
}
